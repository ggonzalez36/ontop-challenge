-- Append-only double-entry ledger (ADR 005).
CREATE TABLE ledger_entry (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id UUID                     NOT NULL REFERENCES transfer (id),
    account     VARCHAR(64)              NOT NULL,
    debit       NUMERIC(19, 2)           NOT NULL,
    credit      NUMERIC(19, 2)           NOT NULL,
    currency    VARCHAR(3)               NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_ledger_one_side CHECK (debit >= 0 AND credit >= 0 AND (debit = 0 OR credit = 0))
);

CREATE INDEX idx_ledger_transfer_account ON ledger_entry (transfer_id, account);

-- Transactional outbox, published to Kafka by the relay.
CREATE TABLE outbox_event (
    id           UUID PRIMARY KEY,
    aggregate_id UUID                     NOT NULL,
    event_type   VARCHAR(50)              NOT NULL,
    payload      VARCHAR(4000)            NOT NULL,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_outbox_pending ON outbox_event (published_at, occurred_at);

-- History read model: one row per wallet movement (withdrawal or refund).
CREATE TABLE wallet_movement (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT                   NOT NULL,
    transfer_id UUID                     NOT NULL REFERENCES transfer (id),
    type        VARCHAR(20)              NOT NULL,
    amount      NUMERIC(19, 2)           NOT NULL,
    currency    VARCHAR(3)               NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_wallet_movement_user ON wallet_movement (user_id, occurred_at DESC, id DESC);

-- ShedLock: only one instance runs each scheduled job at a time.
CREATE TABLE shedlock (
    name       VARCHAR(64)  NOT NULL PRIMARY KEY,
    lock_until TIMESTAMP    NOT NULL,
    locked_at  TIMESTAMP    NOT NULL,
    locked_by  VARCHAR(255) NOT NULL
);
